import { expect, test } from '@playwright/test'

test('a first visit is empty and keyboard search distinguishes C12 from I12', async ({ page }) => {
  await page.goto('./')
  await expect(page.getByText('Select your group above')).toBeVisible()
  const search = page.getByRole('combobox', { name: 'Group code' })
  await expect(search).toHaveValue('')
  await page.keyboard.press('Tab')
  await page.keyboard.press('Tab')
  await expect(search).toBeFocused()
  await search.press('ArrowDown')
  await expect(search).toHaveAttribute('aria-activedescendant', 'group-option-C1')
  await expect(page.getByRole('option')).toHaveCount(72)
  await search.press('Escape')
  await expect(page.getByRole('listbox')).toHaveCount(0)
  await search.fill('c12')
  await search.press('ArrowDown')
  await search.press('Enter')
  await expect(page.getByRole('heading', { name: 'Group C12' })).toBeVisible()
  await expect(page.locator('.exam-card')).toHaveCount(5)
  const dates = await page.locator('time').evaluateAll(nodes => nodes.map(node => node.getAttribute('datetime')))
  expect(dates).toEqual(['2026-11-26', '2026-11-27', '2026-12-01', '2026-12-03', '2026-12-05'])
  await expect(page.locator('.exam-card').first()).toContainText('Room 312')
  await search.fill('i12')
  await search.press('Enter')
  await expect(page.getByRole('heading', { name: 'Group I12' })).toBeVisible()
  await expect(page.locator('.exam-card').first()).toContainText('Room 524')
  await expect(page).toHaveURL(/group=I12$/)
  await page.goto('./')
  await expect(search).toHaveValue('I12')
  await page.getByRole('button', { name: 'Clear group' }).click()
  await expect(page.getByText('Select your group above')).toBeVisible()
  await page.reload()
  await expect(search).toHaveValue('')
})

test('direct links load and copy, and the choice of theme survives reload', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  const failed: string[] = []
  const errors: string[] = []
  page.on('response', response => {
    if (response.status() >= 400) failed.push(response.url())
  })
  page.on('requestfailed', request => failed.push(request.url()))
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('./?group=C12')
  await expect(page.getByRole('heading', { name: 'Group C12' })).toBeVisible()
  await expect(page.getByText('Draft schedule', { exact: true })).toHaveCount(0)
  await expect(page.getByText('Draft datesheet.', { exact: true })).toBeVisible()
  await expect(page.getByText('Reporting time is not specified in the datesheet.')).toHaveCount(0)
  await expect(page.locator('html')).toHaveCSS('background-color', 'rgb(239, 241, 245)')
  await page.getByRole('button', { name: 'Copy link' }).click()
  await expect(page.getByRole('button', { name: 'Link copied' })).toBeVisible()
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe(page.url())
  await page.getByRole('button', { name: 'Dark mode' }).click()
  await expect(page.locator('html')).toHaveCSS('background-color', 'rgb(30, 30, 46)')
  await page.reload()
  await expect(page.getByRole('button', { name: 'Light mode' })).toBeVisible()
  await expect(page.locator('html')).toHaveCSS('background-color', 'rgb(30, 30, 46)')
  await page.getByRole('button', { name: 'Light mode' }).click()
  await expect(page.locator('html')).toHaveCSS('background-color', 'rgb(239, 241, 245)')
  const pdfLink = page.getByRole('link', { name: 'View datesheet PDF', exact: true })
  await expect(pdfLink).toBeVisible()
  const reportLink = page.getByRole('contentinfo').getByRole('link', { name: 'Report an issue on GitHub' })
  await expect(reportLink).toBeVisible()
  await expect(reportLink).toHaveAttribute('href', 'https://github.com/neolakshay/externals-lookup/issues/new')
  const pdf = await pdfLink.getAttribute('href')
  const response = await page.request.get(pdf!)
  expect(response.ok()).toBe(true)
  expect((await response.body()).subarray(0, 5).toString()).toBe('%PDF-')
  expect(await page.evaluate(async () => {
    await document.fonts.ready
    return [...document.fonts].some(font => font.family.includes('DM Sans') && font.status === 'loaded')
  })).toBe(true)
  expect(failed).toEqual([])
  expect(errors).toEqual([])
})

test('invalid and similarly written group codes recover through search and history', async ({ page }) => {
  await page.goto('./?group=I12')
  await expect(page.getByRole('heading', { name: 'Group I12' })).toBeVisible()
  await page.goto('./?group=__proto__')
  await expect(page.getByText('Group not found.')).toBeVisible()
  const search = page.getByRole('combobox')
  await search.fill('O12')
  await expect(page.getByText('No matching group.')).toBeVisible()
  await search.fill('c (aiml) 9')
  await search.press('Enter')
  await expect(page.getByRole('heading', { name: 'Group C(AIML)9' })).toBeVisible()
  await page.goBack()
  await expect(page.getByText('Group not found.')).toBeVisible()
  await page.goForward()
  await expect(page.getByRole('heading', { name: 'Group C(AIML)9' })).toBeVisible()
})

test('the shared slot is visible alongside, and separate from, both individual schedules', async ({ page }) => {
  await page.goto('./?group=EE4')
  await expect(page.getByText('Confirm your slot with MAIT.')).toBeVisible()
  await expect(page.locator('.exam-card').first()).toContainText('9:00 AM – 11:30 AM')
  await expect(page.locator('.shared-time')).toHaveCount(4)
  await expect(page.locator('.shared-time').first()).toContainText('EE4/ME4 at 11:30 AM – 2:00 PM')
  await page.goto('./?group=ME4')
  await expect(page.locator('.exam-card').first()).toContainText('2:00 PM – 4:30 PM')
  await expect(page.locator('.shared-time')).toHaveCount(4)
  await page.goto('./?group=EE4%2FME4')
  await expect(page.getByRole('heading', { name: 'Group EE4/ME4' })).toBeVisible()
  await expect(page.locator('.exam-card').first()).toContainText('11:30 AM – 2:00 PM')
  await expect(page.locator('.shared-time')).toHaveCount(0)
})

